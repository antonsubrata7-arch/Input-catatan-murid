export function getDisciplineStatus(points: number): DisciplineStatus {
  if (points >= 75) return 'Panggilan Keras / Skorsing';
  if (points >= 50) return 'Panggilan Ortu II';
  if (points >= 25) return 'Panggilan Ortu I';
  if (points >= 10) return 'Peringatan Lisan';
  return 'Aman';
}

